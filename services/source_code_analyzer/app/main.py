@app.post("/api/v1/repo/scan", status_code=status.HTTP_200_OK)
async def scan_repo_endpoint(payload: ScanRequest):
    """
    Scan a local repository using the repo_analyzer static analysis library.

    Returns a serialisable summary of the ApplicationProfile: languages,
    frameworks, databases, ports, components, unknowns, conflicts, and
    coverage metrics.  Does NOT call Module 1 (no AWS sizing).
    """
    repo_path = validate_safe_repo_path(payload.repo_path)

    try:
        result = scan_repository(repo_path, include_findings=payload.include_findings)
    except ImportError as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=str(exc),
        )
    except Exception as exc:
        logger.error("Scan failed for %s: %s", repo_path, exc, exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Scan failed: {str(exc)}",
        )

    return result


@app.post("/api/v1/repo/scan-and-size", status_code=status.HTTP_200_OK)
async def scan_and_size_endpoint(payload: DispatchRequest):
    """
    Scan the repository AND forward the inferred tech profile to Module 1
    (``/api/v1/requirements/analyze-repo``) to obtain AWS architecture sizing,
    cost estimates, 'Why That Service' rationales, and FinOps optimizations.

    Returns a combined payload:
    - ``scan_result``  — raw repo fingerprint
    - ``parsed_input`` — the RequirementInput mapped from the scan
    - ``sizing_data``  — full Module 1 output (costs, rationales, AI advice)
    - ``project_id``   — requirements.db record ID (when auto_save=True)
    """
    repo_path = validate_safe_repo_path(payload.repo_path)

    # 1. Local scan
    try:
        scan_result = scan_repository(repo_path, include_findings=False)
    except Exception as exc:
        logger.error("Scan failed: %s", exc, exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Repository scan failed: {str(exc)}",
        )

    # 2. Forward to Module 1 analyze-repo endpoint
    m1_url = payload.module1_url.rstrip("/") + "/api/v1/requirements/analyze-repo"
    m1_payload = {
        "repo_path":    str(repo_path),
        "project_name": payload.project_name,
        "monthly_budget": payload.monthly_budget,
        "traffic_scale":  payload.traffic_scale,
        "reliability":    payload.reliability,
        "target_region":  payload.target_region,
        "auto_save":      payload.auto_save,
    }

    logger.info("Forwarding scan to Module 1: %s", m1_url)
    start = time.time()
    try:
        async with httpx.AsyncClient(timeout=30.0) as client:
            resp = await client.post(m1_url, json=m1_payload)

        if resp.status_code != 200:
            raise HTTPException(
                status_code=status.HTTP_502_BAD_GATEWAY,
                detail=f"Module 1 returned HTTP {resp.status_code}: {resp.text[:300]}",
            )

        m1_data = resp.json()
        elapsed_ms = int((time.time() - start) * 1000)
        logger.info("Module 1 sizing completed in %dms", elapsed_ms)

        return {
            "status":       "SUCCESS",
            "source":       "repository_scan_and_size",
            "repo_path":    str(repo_path),
            "scan_result":  scan_result,
            "parsed_input": m1_data.get("parsed_input"),
            "project_id":   m1_data.get("project_id"),
            "sizing_data":  m1_data.get("data"),
            "dispatch_ms":  elapsed_ms,
            "module1_url":  m1_url,
        }

    except httpx.RequestError as exc:
        logger.error("Could not reach Module 1 (%s): %s", m1_url, exc)
        # Return scan-only result with a warning
        return {
            "status":       "SCAN_ONLY",
            "warning":      f"Module 1 unreachable at {m1_url}: {str(exc)}",
            "repo_path":    str(repo_path),
            "scan_result":  scan_result,
            "parsed_input": None,
            "project_id":   None,
            "sizing_data":  None,
        }


